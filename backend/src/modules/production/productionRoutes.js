const express = require('express');
const { protect } = require('../../middleware/authMiddleware');
const controller = require('./productionSettingsController');
const reports = require('./productionReportController');
const billing = require('./productionBillingController');
const exportsController = require('./productionReportsController');
const router = express.Router();
router.use(protect);
router.get('/report', reports.getReport);
router.get('/reports', exportsController.read);
router.post('/reports/export-authorization', exportsController.authorize);
router.get('/billing', billing.list);
router.post('/billing', billing.create);
router.post('/billing/prepare-review', billing.prepare);
router.post('/billing/review-report', billing.report);
router.get('/billing/:id', billing.read);
router.get('/billing/:id/recalculation-preview', billing.preview);
router.post('/billing/:id/actions', billing.action);
router.get('/settings/catalog', controller.settingsAdmin, reports.getSettingsCatalog);
router.get('/settings/audit', controller.settingsAdmin, controller.listAudit);
router.patch('/settings/employee-project-rates/:employee', controller.settingsAdmin, controller.updateEmployeeRates);
router.post('/settings/classification/batch', controller.settingsAdmin, controller.saveClassificationBatch);
router.post('/settings/classification/batch/historical-corrections', controller.settingsAdmin, controller.historicalClassificationBatch);
router.get('/settings/:kind/history', controller.settingsAdmin, controller.history);
router.get('/settings/:kind', controller.settingsAdmin, controller.listSettings);
router.post('/settings/:kind', controller.settingsAdmin, controller.save);
router.post('/settings/:kind/historical-corrections', controller.settingsAdmin, controller.historicalSave);
module.exports = router;
